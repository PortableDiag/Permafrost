package com.portablediag.permafrost.api;

/** The reference served at {@code GET /api/docs}, and the route list at {@code GET /api}. */
public final class ApiDocs {

    private ApiDocs() {}

    public static final String[] SUMMARY = {
            "GET    /api/health",
            "GET    /api/docs",
            "GET    /api/instance",
            "GET    /api/apps",
            "POST   /api/apps",
            "GET    /api/apps/{package}",
            "PATCH  /api/apps/{package}",
            "DELETE /api/apps/{package}",
            "POST   /api/apps/{package}/freeze",
            "POST   /api/apps/{package}/wake",
            "POST   /api/apps/{package}/launch",
            "POST   /api/apps/{package}/unlock-update",
            "POST   /api/apps/{package}/frost-icon",
            "GET    /api/apps/{package}/icon",
            "GET    /api/installed?q=",
            "GET    /api/settings",
            "PATCH  /api/settings",
            "GET    /api/palettes",
            "GET    /api/crash",
    };

    public static final String MARKDOWN = String.join("\n",
            "# Permafrost local API (v" + ApiRouter.API_VERSION + ")",
            "",
            "Everything the Permafrost UI can do, over HTTP on this phone. Off until switched on",
            "under Settings > Local API. Listens on 127.0.0.1 (port 8791 by default) unless",
            "\"Reachable from the local network\" is on.",
            "",
            "## Auth",
            "",
            "Every route except `GET /api/health` needs the key from Settings, as",
            "`X-API-Key: <key>` or `Authorization: Bearer <key>`. A missing or wrong key is a `401`.",
            "Issuing a new key in Settings stops the old one at once.",
            "",
            "## Conventions",
            "",
            "- JSON in, JSON out. Errors are `{\"error\": \"...\", \"hint\": \"...\"}` with a real status:",
            "  `400` bad request, `401` key, `404` unknown route or unmanaged package, `405` wrong",
            "  method, `409` refused (e.g. no screen lock for the app lock), `500` the device refused",
            "  the operation (the text is what `pm` said), `503` Permafrost has no root.",
            "- Mode is `freeze` (pm disable-user; keeps data) or `ghost` (back up, uninstall,",
            "  reinstall on wake; fragile).",
            "- The device is the source of truth. `dormant` is asked of the device on every call",
            "  (`null` when Permafrost has no root); `state` is one of `frozen`, `ghosted`, `awake`,",
            "  `unlocked_for_update`, `unknown`.",
            "- Root operations run one at a time. A ghost wake can take tens of seconds.",
            "",
            "## Routes",
            "",
            "### `GET /api/health` — no key",
            "`{\"ok\":true,\"app\":\"Permafrost\",\"api\":1}`",
            "",
            "### `GET /api/instance`",
            "Version, SDK, whether root and Usage access are granted, how many apps are managed.",
            "Without Usage access nothing re-freezes on its own: a launched app stays awake.",
            "",
            "### `GET /api/apps`",
            "`{\"root\":bool,\"apps\":[{package,label,mode,state,dormant,update_unlocked,frost_icon,has_backup}]}`",
            "",
            "### `POST /api/apps`",
            "Manage apps and put them to sleep, like the Freeze-app picker.",
            "Body: `{\"packages\":[\"com.example\"], \"mode\":\"freeze\"|\"ghost\", \"frost_icon\":false}`",
            "(`{\"package\":\"...\"}` or a bare array also work). `mode` defaults to the default",
            "method setting. Answers per package: `{\"ok\":bool,\"results\":[{package,ok,error?,app}]}`;",
            "`200` if any succeeded, `409` if none did. An app whose first freeze failed stays",
            "managed (as in the UI) and is reported with its state.",
            "",
            "### `GET /api/apps/{package}`",
            "One managed app. `404` if Permafrost does not manage it.",
            "",
            "### `PATCH /api/apps/{package}`",
            "`{\"mode\":\"freeze\"|\"ghost\"}` — switch method. A dormant app is woken in the old",
            "method and put back to sleep in the new one; leaving ghost deletes its backup.",
            "",
            "### `DELETE /api/apps/{package}`",
            "Stop managing: wakes the app, deletes any ghost backup, disables its frost icon.",
            "",
            "### `POST /api/apps/{package}/freeze`",
            "Put it to sleep now. Also ends an unlock-for-update (this is \"Re-freeze now\").",
            "",
            "### `POST /api/apps/{package}/wake`",
            "Wake it without launching. It stays awake until frozen — nothing watches it.",
            "",
            "### `POST /api/apps/{package}/launch`",
            "Wake if needed, start it (through `am`, since Permafrost is in the background), and",
            "re-freeze it once the user leaves — unless it is unlocked for update. Adds a `warning`",
            "when Usage access is missing, because then it will not re-freeze.",
            "",
            "### `POST /api/apps/{package}/unlock-update`",
            "Wake it and keep it awake (no auto re-freeze, boot leaves it alone) so it can update.",
            "`/freeze` re-locks it.",
            "",
            "### `POST /api/apps/{package}/frost-icon`",
            "Ask the launcher to pin a frost icon. The launcher asks the user to confirm, and most",
            "launchers only do that while Permafrost is on screen: `409` when it refused.",
            "",
            "### `GET /api/apps/{package}/icon`",
            "The frosted icon as `image/png` (cached, so it works for a ghosted app too).",
            "",
            "### `GET /api/installed?q=`",
            "Launchable apps, as in the picker: `{\"apps\":[{package,label,managed}]}`. `q` filters on",
            "label or package, case-insensitive.",
            "",
            "### `GET /api/settings`  ·  `PATCH /api/settings`",
            "```",
            "{",
            "  \"default_mode\": \"freeze\" | \"ghost\",",
            "  \"refreeze_delay_sec\": 0..15,",
            "  \"palette\": \"<name from /api/palettes>\",",
            "  \"dark_mode\": \"system\" | \"light\" | \"dark\",",
            "  \"app_lock\": bool,",
            "  \"lock_frost_icons\": bool,          // needs app_lock",
            "  \"lock_method\": \"biometric\" | \"credential\" | \"none\"   // read-only",
            "}",
            "```",
            "PATCH any subset; it is all validated before anything changes. Turning `app_lock` on",
            "with no device screen lock is a `409`. `dark_mode` only affects palettes that have a",
            "light form (Material You, Ocean, Terminal). The Local API's own settings (on/off, key,",
            "port, LAN) are deliberately not here: change them on the phone.",
            "",
            "### `GET /api/palettes`",
            "The house palettes in picker order: `{name,label,follows_dark_mode,mono,current}`.",
            "",
            "### `GET /api/crash`",
            "The latest crash report as text, without clearing it (the app still shows it once).",
            "`404` when there is none.",
            "");
}
